// ===================== Improv Wi-Fi (browser-configured WiFi over serial) =====================
// Protocol parsing/framing come from the OFFICIAL improv-wifi SDK (github.com/improv-wifi/sdk-cpp,
// PlatformIO package improv/Improv @ 1.2.6 — see platformio.ini). That SDK deliberately ships parser
// + frame-builder only and leaves serial transport to the integrator (no Arduino glue is published
// upstream). The byte layout below ("IMPROV" + version + type + length + data + checksum + '\n') is
// ported from ESPHome's improv_serial component — the reference production implementation built on
// this exact SDK — not hand-rolled. WiFiManager's captive portal (above) remains the primary/fallback
// provisioning path; this only offers a second, browser-native way in during the unprovisioned window.
class ImprovSerialHandler {
 public:
  void begin() {
    if (active_) return;
    active_ = true;
    rxBuffer_.clear();
    lastByteMs_ = 0;
    state_ = improv::STATE_AUTHORIZED;
  }

  void deactivate() { active_ = false; }
  bool active() const { return active_; }

  // millis() of the last command a client got far enough to have parsed, or 0 if none ever did.
  // The boot window uses this to tell "nobody is out there" apart from "somebody is out there,
  // reading the dialog". Line noise cannot set it: only a complete, checksum-valid frame does.
  uint32_t lastClientMs() const { return lastClientMs_; }

  // Byte-at-a-time, non-blocking — safe to call every loop() iteration alongside the other
  // ...->loop() members (webUi.loop(), timeSync.loop()); never blocks on Serial I/O.
  void loop() {
    if (!active_) return;

    if (lastByteMs_ != 0 && millis() - lastByteMs_ > 100) {
      rxBuffer_.clear();
      lastByteMs_ = 0;
    }

    while (Serial.available()) {
      const uint8_t b = (uint8_t)Serial.read();
      const size_t at = rxBuffer_.size();
      rxBuffer_.push_back(b);
      const bool keepGoing = improv::parse_improv_serial_byte(
          at, b, rxBuffer_.data(),
          [this](improv::ImprovCommand cmd) -> bool { return handleCommand(cmd); },
          [this](improv::Error err) { sendError(err); });
      if (keepGoing) {
        lastByteMs_ = millis();
      } else {
        rxBuffer_.clear();
        lastByteMs_ = 0;
      }
    }

    if (state_ == improv::STATE_PROVISIONING) {
      if (WiFi.status() == WL_CONNECTED) {
        Serial.println("[Improv] Wi-Fi connected — provisioning complete.");
        setState(improv::STATE_PROVISIONED);
        sendUrlResponse(improv::WIFI_SETTINGS);
      } else if (millis() - provisioningStartMs_ > WIFI_CONNECT_TIMEOUT_MS) {
        Serial.println("[Improv] Timed out waiting for Wi-Fi connection.");
        sendError(improv::ERROR_UNABLE_TO_CONNECT);
        setState(improv::STATE_AUTHORIZED);
      }
    }
  }

 private:
  bool handleCommand(improv::ImprovCommand cmd) {
    // Anything that parses cleanly means a real client is on the wire, including the browser's
    // opening GET_CURRENT_STATE / GET_DEVICE_INFO handshake, which is what fires while the
    // user is still looking at the dialog, long before any password is typed.
    lastClientMs_ = millis();
    switch (cmd.command) {
      case improv::WIFI_SETTINGS: {
        Serial.printf("[Improv] Wi-Fi settings received: SSID=%s\n", cmd.ssid.c_str());
        // Persist to the SAME "wifi" NVS namespace the /wifi web page and setupWiFi()'s
        // Priority-1 saved-credentials check use, so a later reboot reconnects with no
        // Improv client needed.
        Preferences wprefs;
        wprefs.begin("wifi", false);
        wprefs.putString("ssid", cmd.ssid.c_str());
        wprefs.putString("pass", cmd.password.c_str());
        wprefs.end();
        WiFi.disconnect(false);
        delay(100);
        WiFi.begin(cmd.ssid.c_str(), cmd.password.c_str());
        provisioningStartMs_ = millis();
        setState(improv::STATE_PROVISIONING);
        return true;
      }
      case improv::GET_CURRENT_STATE:
        setState(state_);
        if (state_ == improv::STATE_PROVISIONED) sendUrlResponse(improv::GET_CURRENT_STATE);
        return true;
      case improv::GET_DEVICE_INFO: {
        std::vector<std::string> info = {"ChronoBloom", FIRMWARE_VERSION, "ESP32-C3", DEVICE_TITLE};
        sendResponse(improv::GET_DEVICE_INFO, info);
        return true;
      }
      case improv::GET_WIFI_NETWORKS:
        // Scanning isn't wired up here — WiFiManager's portal already covers scan+select.
        // Send the empty terminator the protocol expects so clients don't hang waiting.
        sendResponse(improv::GET_WIFI_NETWORKS, std::vector<std::string>{});
        return true;
      default:
        sendError(improv::ERROR_UNKNOWN_RPC);
        return false;
    }
  }

  void setState(improv::State state) {
    state_ = state;
    const uint8_t data[1] = {(uint8_t)state};
    sendFrame(improv::TYPE_CURRENT_STATE, data, 1);
  }

  void sendError(improv::Error err) {
    const uint8_t data[1] = {(uint8_t)err};
    sendFrame(improv::TYPE_ERROR_STATE, data, 1);
  }

  void sendUrlResponse(improv::Command command) {
    char url[64];
    snprintf(url, sizeof(url), "http://%s.local/", DEVICE_HOSTNAME);
    sendResponse(command, std::vector<std::string>{std::string(url)});
  }

  void sendResponse(improv::Command command, const std::vector<std::string> &data) {
    const std::vector<uint8_t> payload = improv::build_rpc_response(command, data, false);
    sendFrame(improv::TYPE_RPC_RESPONSE, payload.data(), payload.size());
  }

  // Wire format: "IMPROV" (6) + version (1) + type (1) + length (1) + <length> data bytes +
  // checksum (1) + '\n'. Checksum = sum of every byte before it, truncated to uint8_t.
  void sendFrame(uint8_t type, const uint8_t *data, size_t len) {
    const uint8_t header[9] = {'I', 'M', 'P', 'R', 'O', 'V',
                                improv::IMPROV_SERIAL_VERSION, type, (uint8_t)len};
    uint8_t checksum = 0;
    for (uint8_t hb : header) checksum += hb;
    for (size_t i = 0; i < len; i++) checksum += data[i];
    Serial.write(header, sizeof(header));
    if (len > 0) Serial.write(data, len);
    Serial.write(checksum);
    Serial.write('\n');
  }

  bool active_ = false;
  improv::State state_ = improv::STATE_AUTHORIZED;
  std::vector<uint8_t> rxBuffer_;
  uint32_t lastByteMs_ = 0;
  uint32_t lastClientMs_ = 0;
  uint32_t provisioningStartMs_ = 0;
};

