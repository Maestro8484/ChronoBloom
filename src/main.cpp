  void animHr2(uint32_t now) {  // Galaxy Spin — spiral arms, dark space, stars
    const uint32_t se = scaledElapsed(now - animStartMs_);
    const uint32_t dur = 9000;
    if (se >= dur) { animPhase_ = ANIM_IDLE; return; }
    strip_.setBrightness(animEnv(se, dur, 500, 1000));
    // Base phases are true quarter turns (64 = 90°, 128 = 180° in 0-255 units)
    // and the middle arm counter-rotates, matching the shared ring
    // choreography used by the comet/orbit animations.
    uint8_t outerOff  = (uint8_t)(se * 256u / 6000u);
    uint8_t middleOff = (uint8_t)(64u - (uint8_t)(se * 256u / 8000u));
    uint8_t innerOff  = (uint8_t)(128u + (uint8_t)(se * 256u / 5000u));
    // Slow global hue drift: the arms cycle through the palette across the
    // 9s run instead of holding one flat color band — far more color
    // variation on camera than the old single-hue spin.
    uint8_t hueDrift = (uint8_t)(se * 96u / dur);
    // Brightness rides galaxyWave() for EVERY palette (not just the
    // ring-mapped one), carving dark lanes between two bright spiral arms so
    // the "space vs. stars" contrast is always present. Stars live in the
    // dark lanes and twinkle on their own staggered cycles.
    //
    // Two fades keep a star from ever popping, both inside starLit(): its
    // twinkle cycle eases it in and out over time, and lane depth fades it
    // out spatially as the rotating arm sweeps toward it — without that, a
    // lit star sitting at w=69 blinked out in one frame the instant the arm
    // pushed it to w=70. Stars are max-blended over the arm color rather
    // than replacing it, so a dimming star melts into the arm instead of
    // punching a hole in it.
    for (uint8_t i = 0; i < RING_OUTER_60.count; i++) {
      uint8_t frac = (uint8_t)(outerOff + i * 256u / RING_OUTER_60.count);
      uint8_t w = galaxyWave(frac);
      uint32_t base = scale(bandColor(0, (uint8_t)(frac + hueDrift)), w);
      uint8_t star = starLit((uint16_t)(0x100u + i), se, w);
      if (star) {
        uint32_t tint = (hash8((uint16_t)(i * 17u + 5u)) & 1u)
            ? gammaColor(255, 250, 235)   // warm white
            : gammaColor(225, 235, 255);  // cool white
        base = blendMax(base, scale(tint, star));
      }
      setRingPixel(RING_OUTER_60, i, base);
    }
    for (uint8_t i = 0; i < RING_MIDDLE_24.count; i++) {
      uint8_t frac = (uint8_t)(middleOff + i * 256u / RING_MIDDLE_24.count);
      uint8_t w = galaxyWave(frac);
      uint32_t base = scale(bandColor(1, (uint8_t)(frac + hueDrift)), w);
      uint8_t star = starLit((uint16_t)(0x200u + i), se, w);
      if (star) {
        uint32_t tint = (hash8((uint16_t)(i * 23u + 11u)) & 1u)
            ? gammaColor(255, 250, 235)
            : gammaColor(225, 235, 255);
        base = blendMax(base, scale(tint, star));
      }
      setRingPixel(RING_MIDDLE_24, i, base);
    }
    for (uint8_t i = 0; i < RING_INNER_12.count; i++) {
      uint8_t frac = (uint8_t)(innerOff + i * 256u / RING_INNER_12.count);
      setRingPixel(RING_INNER_12, i,
                   scale(bandColor(2, (uint8_t)(frac + hueDrift)), galaxyWave(frac)));
    }
    // Galactic core: slow sine breath (was a random jitter every 90ms, which
    // read as flicker rather than a calm pulse).
    float coreFt = (float)se * 6.2832f / 2400.0f;
    uint8_t coreTw = (uint8_t)(190u + (uint8_t)(32.5f + 32.5f * sinf(coreFt)));
    setCenterPixel(scale(bandColor(3, (uint8_t)(outerOff + 128u + hueDrift)), coreTw));
  }

