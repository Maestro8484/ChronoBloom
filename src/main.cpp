  const char* lastAnimSource() const { return lastAnimSource_; }
  uint8_t lastAnimMode() const { return lastAnimMode_; }

  // Master dimmer for demo cross-dissolves. 255 = normal. Set < 255 to fade the
  // whole display (face + animations) toward black; DemoMode ramps this to make
  // every transition a gentle dissolve. Always reset to 255 when demo stops.
  void setMasterFade(uint8_t f) { masterFade_ = f; }
  uint8_t masterFade() const { return masterFade_; }

  // ── Demo-reel Live Run controller (latched reel mode + on-device dissolve) ──
  // The demo reel designer's Live Run plays a curated sequence of animations on
  // the real clock. This OWNS the display the same way DemoMode does: while reel
  // mode is LATCHED (reelActive_), the live clock face is NEVER drawn between
  // animations — the main loop draws pure black instead (see reelRendersFaceNow()
  // / renderTransitionBlack). Face-suppression is a LATCH, not a timed window,
  // so a slow browser, an overrunning animation, or a paused step can no longer
  // make the face flash back in between beats (the v2.12.3 defect: its per-
  // animation safety windows expired in the gaps and the loop fell through to the
  // face render). Cross-dissolves are generated ON DEVICE off the animation
  // start/end edges — the same masterFade_ model DemoMode uses — so every
  // animation gently fades in from black, and the browser only has to say
  // "begin reel / fire trigger / end reel", never micro-manage fade phases.
  //
  // beginReel: latch on, gently fade the live face OUT (leaving it), then hold
  //   black. `safetyMs` is a crash-guard only: if the browser stops driving and
  //   no animation is on screen for this long, the clock returns to its face.
  void beginReel(uint32_t now, uint32_t safetyMs) {
    reelActive_ = true;
    reelClosing_ = false;
    reelWasAnimating_ = animating();
    reelSafetyMs_ = (uint16_t)(safetyMs ? safetyMs : REEL_SAFETY_MS);
    reelSafetyDeadlineMs_ = now + reelSafetyMs_;
    startReelFade(now, masterFade_, 0, REEL_FADE_MS, /*faceFade=*/true);  // dissolve the face out
  }
  // endReel: unlatch and gently fade back UP to the live face from wherever the
  //   dimmer is now. Used for reel steps that intentionally show the face
  //   (brightness cycle / idle / end card) and at Live Run end/abort.
  void endReel(uint32_t now) {
    if (!reelActive_ && !reelClosing_) return;
    reelActive_ = false;
    reelClosing_ = true;
    startReelFade(now, masterFade_, 255, REEL_FADE_MS, /*faceFade=*/true);  // dissolve back to face
  }
  // Hard reset — no dissolve. For paths that seize the display (Start Demo).
  void clearReel() {
    reelActive_ = false; reelClosing_ = false; reelFadeStartMs_ = 0;
    reelSafetyDeadlineMs_ = 0; masterFade_ = 255;
  }
  // Refresh the crash-guard whenever the browser proves it's still driving
  // (each /previewAnimation) so the guard only counts down during genuine idle.
  void noteReelActivity(uint32_t now) {
    if (reelActive_) reelSafetyDeadlineMs_ = now + reelSafetyMs_;
  }
  // True while reel mode owns the display: latched, or finishing its close fade.
  bool reelModeActive() const { return reelActive_ || reelClosing_; }
  // When reel mode owns the display and no animation is playing, should the loop
  // draw the live face (true) or pure black (false)? The face is legitimate only
  // while dissolving the face itself OUT (reel open) or back IN (reel close);
  // every other idle beat is the dark breather between animations → black.
  bool reelRendersFaceNow() const { return reelFadeStartMs_ != 0 && reelFaceFade_; }

  // Advance the reel dimmer every loop() iteration (like DemoMode::updateFade),
  // gated by the caller on !demoMode.active(). Drives the open/close face fades,
  // and auto-arms a dissolve on each animation edge: snap to black when one ends
  // (it already self-faded via its own release envelope), fade in from black
  // when the next begins. No-op when reel mode is entirely idle.
  void tickReelMode(uint32_t now) {
    // 1) advance any in-flight fade (open face-out, close face-in, per-anim fade-in)
    if (reelFadeStartMs_ != 0) {
      const uint32_t e = now - reelFadeStartMs_;
      if (reelFadeDurMs_ == 0 || e >= reelFadeDurMs_) {
        masterFade_ = reelFadeTo_;
        reelFadeStartMs_ = 0;
        if (reelClosing_) { reelClosing_ = false; masterFade_ = 255; }  // fully back to face
      } else {
        const int32_t span = (int32_t)reelFadeTo_ - (int32_t)reelFadeFrom_;
        // Ease the ramp (smooth in/out) instead of a constant-rate linear slope:
        // a dissolve that starts and ends gently reads far less "abrupt", and the
        // eased curve also masks any frame-timing unevenness better than a linear
        // one. Same duration, just a softer shape.
        const uint8_t frac  = (uint8_t)(255u * e / reelFadeDurMs_);   // 0..255 linear progress
        const uint8_t eased = ease8(frac);                            // smoothstep
        masterFade_ = (uint8_t)((int32_t)reelFadeFrom_ + span * (int32_t)eased / 255);
      }
    }
    if (!reelActive_) return;  // any close fade was handled above; nothing else to do
    // 2) keep the crash-guard from expiring while an animation is actually on screen
    if (animating()) {
      reelSafetyDeadlineMs_ = now + reelSafetyMs_;
    } else if ((int32_t)(now - reelSafetyDeadlineMs_) >= 0) {
      endReel(now); return;                                            // browser vanished → recover
    }
    // 3) auto-dissolve on the animation edges
    const bool nowAnim = animating();
    if (reelWasAnimating_ && !nowAnim) {
      reelFadeStartMs_ = 0; masterFade_ = 0;                           // anim ended → hold black
    } else if (!reelWasAnimating_ && nowAnim) {
      startReelFade(now, 0, 255, REEL_FADE_MS, /*faceFade=*/false);    // anim began → fade it in
    }
    reelWasAnimating_ = nowAnim;
  }

