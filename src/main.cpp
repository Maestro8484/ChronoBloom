  // ---- Ring-palette color model --------------------------------------------
  // Every mood palette is four explicit ring colors — outer, middle, inner,
  // center — rendered SOLID per ring (src/anim_palettes.h). This mirrors
  // palette 7 ("Clock colors"), which paints each ring in one configured face
  // color. Nothing sweeps a gradient across a ring, so each ring reads as its
  // own color instead of drowning as one pixel in a mostly-one-hue sweep — the
  // FastLED/WLED way: assign a color to a region. animationPalette (chimes) and
  // reminderPalette (nudges) both index this same 5-option list (v2.27.0).
  // Callers still pass a `frac` position, but it is
  // ignored; each ring is one color. Themed fills route through
  // bandColor()/bloomColor()/paletteColor() — never hardcode strip_.Color()
  // for a themed fill (raw colors must go through gammaColor() to stay corrected;
  // strip_.Color() is only for compositing already-corrected pixels — blendMax/
  // blendOver/scale/dim). Darkness comes from animation envelopes, not the palette.

  // Effective palette index for the active context, with the non-persistent
  // preview override applied. Shared 5-option convention (v2.27.0): indices
  // 0..MOOD_PALETTE_COUNT-1 = mood palettes, 7 = Clock colors (face-mapped,
  // resolved by the callers below). reminderCtx selects reminderPalette (nudge
  // runs) vs animationPalette (interval chimes).
  uint8_t curPalette(bool reminderCtx) const {
    const ClockSettings &s = settings_.get();
    if (reminderCtx)
      return reminderPaletteOverride_ >= 0 ? (uint8_t)reminderPaletteOverride_
                                           : s.reminderPalette;
    return paletteOverride_ >= 0 ? (uint8_t)paletteOverride_ : s.animationPalette;
  }

  // Raw ring color for a band (0=outer,1=middle,2=inner,3=center), scaled by
  // br, from the shared mood ring set (MOOD_PALETTE_RINGS). reminderCtx picks
  // reminderPalette vs animationPalette. Palette 7 (Clock colors) is handled by
  // the callers (configured face colors), never here — a stray 7 reaching this
  // fallback maps to mood 0.
  uint32_t anchorColor(uint8_t band, uint8_t br, bool reminderCtx) {
    band &= 3;
    uint8_t pal = curPalette(reminderCtx);
    if (pal >= MOOD_PALETTE_COUNT) pal = 0;  // 7/Clock colors resolved by callers
    const uint8_t *c = MOOD_PALETTE_RINGS[pal][band];
    return ringColor(c[0], c[1], c[2], br);
  }

  // Palette color for a raw 0-255 position: quadrant-maps position to a ring
  // band (0-63 outer, 64-127 middle, 128-191 inner, 192-255 center). Palette 7
  // maps the same quadrants onto the configured face colors.
  uint32_t paletteColor(uint8_t position, bool useReminderPalette = false) {
    const uint8_t br = animBr();
    const uint8_t band = (uint8_t)(position >> 6);
    const bool reminderCtx = useReminderPalette || reminderPaletteActive_;
    if (curPalette(reminderCtx) == 7) {  // Clock colors: quadrant-mapped face colors
      const ClockSettings &s = settings_.get();
      switch (band) {
        case 0:  return ringColor(s.outerMarkerRed, s.outerMarkerGreen, s.outerMarkerBlue, br);
        case 1:  return ringColor(s.hoursRed, s.hoursGreen, s.hoursBlue, br);
        case 2:  return ringColor(s.innerHourRed, s.innerHourGreen, s.innerHourBlue, br);
        default: return ringColor(s.centerRed, s.centerGreen, s.centerBlue, br);
      }
    }
    return anchorColor(band, br, reminderCtx);
  }

  // Palette color for a ring band rather than a raw palette position.
  // band: 0=outer, 1=middle, 2=inner, 3=center. frac is the 0-255 position
  // around that ring for palettes that render a gradient. Ring-mapped
  // palette 7 ignores frac and returns the band's actual configured face
  // color — previously animations sampled palette 7 by LED position, which
  // striped every ring into four quadrant colors (position 0-63 = outer
  // marker color, 64-127 = minutes, ...) instead of showing each ring in
  // its own assigned color.
  uint32_t bandColor(uint8_t band, uint8_t frac, bool useReminderPalette = false) {
    const ClockSettings &s = settings_.get();
    const bool reminderCtx = useReminderPalette || reminderPaletteActive_;
    if (curPalette(reminderCtx) == 7) {
      // Weighted-band fidelity: scale each band by its ring's configured
      // level relative to the brightest configured band, so animations keep
      // the face/hand contrast hierarchy the user tuned instead of blasting
      // every ring at one flat animationBrightness. The brightest ring still
      // hits the Peak Brightness setting exactly; the rest hold their
      // configured ratios against it.
      // levels[] follows the band order: 0=outer, 1=middle, 2=inner, 3=center.
      const uint8_t levels[4] = {s.outerMarkerLevel, s.hoursLevel, s.secondsLevel, s.centerLevel};
      uint8_t maxLevel = 1;
      for (uint8_t i = 0; i < 4; ++i) if (levels[i] > maxLevel) maxLevel = levels[i];
      const uint8_t br = (uint8_t)((uint16_t)animBr() * levels[band & 3] / maxLevel);
      switch (band) {
        case 0:  return ringColor(s.outerMarkerRed, s.outerMarkerGreen, s.outerMarkerBlue, br);
        case 1:  return ringColor(s.hoursRed, s.hoursGreen, s.hoursBlue, br);
        // Animations render each band as one solid-color ring, unlike the
        // idle face where innerHourColor is deliberately matched to the
        // middle hand's hoursColor for visual continuity between the two
        // hour indicators. That match makes the middle-24 and inner-12
        // rings visually fuse into one ring during animations. Use
        // secondsColor instead — already part of the clock's configured
        // palette, and distinct from outer/middle/center — so the inner
        // ring reads as its own ring against the two rings outside it.
        // Idle-face rendering (renderFace) is untouched; only animations.
        case 2:  return ringColor(s.secondsRed, s.secondsGreen, s.secondsBlue, br);
        default: return ringColor(s.centerRed, s.centerGreen, s.centerBlue, br);
      }
    }
    // Mood palettes: one solid ring color (frac ignored).
    (void)frac;
    return anchorColor(band, animBr(), reminderCtx);
  }

  // Theme-faithful bloom color for a ring band, center-outward:
  //   band 0 = outer (marker), 1 = middle (hours hand), 2 = inner (inner-hour
  //   hand), 3 = center. Differs from bandColor() only for the ring-mapped
  //   clock palette (7): the inner band returns innerHourColor — the inner
  //   ring's own configured hour-hand color — instead of secondsColor. A bloom
  //   is meant to reproduce the clock face's concentric colors, with center +
  //   inner + middle all reading in the warm hour family and the outer ring in
  //   the marker color; the rings fusing into one flower is the intent. Comets
  //   are the opposite (rings must stay distinct as they scroll), which is why
  //   bandColor() keeps the contrasting secondsColor inner mapping for those.
  //   For the mood ring palettes this is identical to bandColor():
  //   each ring is one solid anchor color (frac ignored).
  uint32_t bloomColor(uint8_t band, uint8_t frac) {
    const ClockSettings &s = settings_.get();
    const bool reminderCtx = reminderPaletteActive_;
    if (curPalette(reminderCtx) == 7) {
      const uint8_t levels[4] = {s.outerMarkerLevel, s.hoursLevel,
                                 s.innerHourLevel, s.centerLevel};
      uint8_t maxLevel = 1;
      for (uint8_t i = 0; i < 4; ++i) if (levels[i] > maxLevel) maxLevel = levels[i];
      const uint8_t br = (uint8_t)((uint16_t)animBr() * levels[band & 3] / maxLevel);
      switch (band & 3) {
        case 0:  return ringColor(s.outerMarkerRed, s.outerMarkerGreen, s.outerMarkerBlue, br);
        case 1:  return ringColor(s.hoursRed, s.hoursGreen, s.hoursBlue, br);
        case 2:  return ringColor(s.innerHourRed, s.innerHourGreen, s.innerHourBlue, br);
        default: return ringColor(s.centerRed, s.centerGreen, s.centerBlue, br);
      }
    }
    // Mood palettes: one solid ring color (frac ignored).
    (void)frac;
    return anchorColor(band, animBr(), reminderCtx);
  }

  // Every palette now renders solid per ring (mood ring set and palette 7
  // alike), so animations are always ring-mapped.
  bool animPaletteRingMapped() const { return true; }

  // Style values with the non-persistent preview override applied.
  uint8_t animBr() const {
    return brightnessOverride_ >= 0 ? (uint8_t)brightnessOverride_
                                    : settings_.get().animationBrightness;
  }
  uint8_t animTl() const {
    return trailOverride_ >= 0 ? (uint8_t)trailOverride_
                               : settings_.get().trailLength;
  }

  // Quadratic ease-in-out on a 0-255 ramp. Linear brightness ramps read as
  // visible steps on WS2812s, especially at the dim end; easing both ends
  // of every envelope is most of what "smooth" looks like on these LEDs.
  static uint8_t ease8(uint8_t x) {
    if (x < 128) { const uint16_t t = x; return (uint8_t)((t * t) >> 7); }
    const uint16_t t = 255 - x;
    return (uint8_t)(255 - ((t * t) >> 7));
  }

  // Perceptual (approx gamma-2) scale for trail falloff and fade tails.
  static uint8_t gamma8(uint8_t v) { return (uint8_t)(((uint16_t)v * v) / 255); }

  // Two-arm spiral brightness wave with a true-black floor: two bright arms
  // per revolution separated by dark "space". Gamma-shaped so the arms punch
  // and the gaps read as genuinely dark, not merely dim — this is what gives
  // Galaxy Spin its light/dark contrast on every palette (gradient palettes
  // used to render flat full-brightness with no dark lanes at all).
  static uint8_t galaxyWave(uint8_t frac) {
    uint8_t f = (uint8_t)(frac * 2u);  // two peaks per revolution
    uint8_t tri = f < 128 ? (uint8_t)(f * 2u) : (uint8_t)((255u - f) * 2u);
    return gamma8(tri);
  }

  // Cheap 8-bit hash for star/twinkle placement — no PRNG state on the hot
  // render path. Same input always maps to the same pixel, so stars hold
  // still for a frame window instead of buzzing every tick.
  static uint8_t hash8(uint16_t x) {
    x ^= (uint16_t)(x >> 7); x = (uint16_t)(x * 0x2C9Bu); x ^= (uint16_t)(x >> 5);
    return (uint8_t)x;
  }

  // Shared twinkle engine: Galaxy Spin's stars and the Firefly nudge both
  // ride this. Each pixel id owns a phase-offset breathing cycle of periodMs;
  // a per-(pixel,cycle) hash decides whether that cycle hosts a light at all
  // (hitThresh/256 of them), and it eases in and out within the cycle.
  // Replaces a synchronized full-white hash-gate that popped every star on
  // the same global tick — on camera that read as a strobe, not starlight.
  // Returns 0 when this pixel is dark for this cycle.
  static uint8_t twinkleLevel(uint16_t pixId, uint32_t se, uint32_t periodMs, uint8_t hitThresh) {
    uint32_t local = se + (uint32_t)hash8(pixId) * 11u;
    uint16_t cyc = (uint16_t)(local / periodMs);
    if (hash8((uint16_t)(pixId * 31u + cyc)) >= hitThresh) return 0;
    uint8_t ph = (uint8_t)((local % periodMs) * 255u / periodMs);
    uint8_t tri = ph < 128 ? (uint8_t)(ph * 2u) : (uint8_t)((255u - ph) * 2u);
    return gamma8(ease8(tri));
  }
  // Galaxy Spin stars: ~1.4s breath, ~22% of cycles host a star.
  static uint8_t starLevel(uint16_t pixId, uint32_t se) {
    return twinkleLevel(pixId, se, 1400u, 56u);
  }

  // Star brightness at a pixel, given how deep into a dark lane it sits.
  // `w` is the spiral-arm wave: 0 = deepest lane, >=STAR_LANE = full arm.
  // Fading with lane depth means the rotating arm dissolves a star instead of
  // clipping it off. Peak caps at ~78% so starlight never reads as a flash.
  static uint8_t starLit(uint16_t pixId, uint32_t se, uint8_t w) {
    static constexpr uint8_t STAR_LANE = 70;   // arm threshold
    static constexpr uint8_t STAR_PEAK = 200;  // ~78% of full white
    if (w >= STAR_LANE) return 0;
    uint8_t lvl = starLevel(pixId, se);
    if (!lvl) return 0;
    uint8_t depth = (uint8_t)(((uint16_t)(STAR_LANE - w) * 255u) / STAR_LANE);
    uint16_t v = (uint16_t)lvl * depth / 255u;
    return (uint8_t)(v * STAR_PEAK / 255u);
  }

  // Per-channel max. Used to lay a star/firefly over an existing pixel so the
  // overlay can fade to nothing without ever darkening what's underneath.
  uint32_t blendMax(uint32_t a, uint32_t b) {
    uint8_t ar = (a >> 16) & 0xFF, ag = (a >> 8) & 0xFF, ab = a & 0xFF;
    uint8_t br = (b >> 16) & 0xFF, bg = (b >> 8) & 0xFF, bb = b & 0xFF;
    return strip_.Color(ar > br ? ar : br, ag > bg ? ag : bg, ab > bb ? ab : bb);
  }

  // Standard "over" alpha-composite: lay `top` onto `base` at opacity `a`
  // (0=base only, 255=top only). Per-channel lerp. Used by the second-hand
  // trail and progress arc so they blend into the face hue underneath and fade
  // toward the outer-marker/filler/minute color instead of punching to black —
  // a plain setRingPixel overwrite darkened the tail to nothing (the same
  // dark-hole failure blendMax was written to avoid).
  uint32_t blendOver(uint32_t base, uint32_t top, uint8_t a) {
    if (a == 0) return base;
    if (a == 255) return top;
    const uint16_t ia = 255u - a;
    uint8_t br = (base >> 16) & 0xFF, bg = (base >> 8) & 0xFF, bb = base & 0xFF;
    uint8_t tr = (top >> 16) & 0xFF, tg = (top >> 8) & 0xFF, tb = top & 0xFF;
    return strip_.Color((uint8_t)(((uint16_t)tr * a + (uint16_t)br * ia) / 255u),
                        (uint8_t)(((uint16_t)tg * a + (uint16_t)bg * ia) / 255u),
                        (uint8_t)(((uint16_t)tb * a + (uint16_t)bb * ia) / 255u));
  }

  // Focus-reminder brightness ceiling. A "nudge" for hyperfocus interruption
  // must read as a gentle swell, never a full-intensity alert flash. Every
  // reminder animation scales its peak to this fraction of animBr() (~80%).
  static constexpr uint8_t NUDGE_CEIL = 205;

  // Warm golden flower-core (stamen) for bloom animations, so the center +
  // inner ring read as a bright warm heart regardless of the selected
  // palette — the ChronoBloom flower metaphor, from the inside out:
  // stamen (center / inner-12) → stigma (middle-24) → petals (outer-60).
  uint32_t stamenColor(uint8_t br) {
    // Warm gold (255,205,55) corrected once, then dimmed to br — same chokepoint
    // as every themed color, so the bloom core stays consistent with the face.
    return scale(gammaColor(255, 205, 55), br);
  }

  // Eased attack/sustain/release brightness envelope for a whole animation:
  // 0 → animBr() over `attack` ms, hold, back to 0 over the final `release`
  // ms of `dur`. Caller guarantees se < dur.
  uint8_t animEnv(uint32_t se, uint32_t dur, uint32_t attack, uint32_t release) {
    const uint8_t br = animBr();
    uint8_t lin;
    if (se < attack)             lin = (uint8_t)(se * 255u / attack);
    else if (dur - se < release) lin = (uint8_t)((dur - se) * 255u / release);
    else                         return br;
    return (uint8_t)(((uint16_t)ease8(lin) * br) / 255u);
  }

  // Trail pixel brightness: linear falloff by tap index, gamma-weighted so
  // the tail fades out perceptually instead of in four visible chunks.
  // ── Ring choreography ────────────────────────────────────────────────────
  // One convention for every multi-ring travelling effect, so they all read as
  // the same mirrored bloom instead of each animation inventing its own
  // stagger. Ring index: 0 = outer-60, 1 = middle-24, 2 = inner-12.
  //   * Phase: each ring starts a quarter turn (90°) ahead of the ring outside
  //     it — ringIdx * count/4 LEDs.
  //   * Mirror: odd rings travel backwards, so adjacent rings counter-rotate.
  // `travelled` is the head's distance in LEDs along this ring (pre-wrap).
  static uint8_t choreoPos(const RingConfig &ring, uint8_t ringIdx, uint32_t travelled) {
    const uint8_t n = ring.count;
    uint8_t p = (uint8_t)(travelled % n);
    if (ringIdx & 1u) p = (uint8_t)(n - 1u - p);                 // mirror
    const uint8_t phase = (uint8_t)(((uint16_t)n * ringIdx) / 4u);  // 90° per ring
    return (uint8_t)((p + phase) % n);
  }

  // Trail pixel `t` steps behind a choreoPos() head. A mirrored ring travels
  // backwards, so its tail lies on the opposite side of the head.
  static uint8_t choreoTrail(const RingConfig &ring, uint8_t ringIdx, uint8_t pos, uint8_t t) {
    const uint8_t n = ring.count;
    return (ringIdx & 1u) ? (uint8_t)((pos + t) % n)
                          : (uint8_t)((pos + n - t) % n);
  }

  static const RingConfig &ringByIdx(uint8_t ringIdx) {
    return ringIdx == 0 ? RING_OUTER_60 : (ringIdx == 1 ? RING_MIDDLE_24 : RING_INNER_12);
  }

  static uint8_t trailLevel(uint8_t tap, uint8_t tl) {
    return gamma8((uint8_t)(255u * (tl - tap + 1u) / (tl + 1u)));
  }

  // Opacity (alpha) for the clock-face second-hand trail. `i` = tap index
  // behind the head (0 = pixel just behind the head), `tl` = trail length,
  // `style` = 0 geometric (halving), 1 linear, 2 smooth (gamma). Peaks near
  // TRAIL_PEAK_A just behind the head and eases toward transparent at the tail
  // so blendOver leaves the far tail reading as the face color.
  static uint8_t trailAlpha(uint8_t i, uint8_t tl, uint8_t style) {
    static constexpr uint8_t TRAIL_PEAK_A = 150;  // strongest tint, just behind the head
    if (i >= tl) return 0;
    switch (style) {
      case 0:  // geometric: each tap ~half the previous
        return (uint8_t)(TRAIL_PEAK_A >> i);
      case 1:  // linear falloff to ~0 at the tail
        return (uint8_t)((uint16_t)TRAIL_PEAK_A * (tl - i) / tl);
      default: // smooth: reuse the gamma-weighted trailLevel shape
        return (uint8_t)((uint16_t)TRAIL_PEAK_A * trailLevel((uint8_t)(i + 1u), tl) / 255u);
    }
  }

  uint32_t scaledElapsed(uint32_t elapsed) {
    const uint8_t spd = speedOverride_ >= 1 ? (uint8_t)speedOverride_
                                            : settings_.get().animationSpeed;
    static const uint8_t num[] = {1, 3, 4, 6, 8};
    static const uint8_t den[] = {2, 4, 4, 4, 4};
    const uint8_t idx = (spd < 1) ? 0u : (spd > 5) ? 4u : (uint8_t)(spd - 1);
    return elapsed * num[idx] / den[idx];
  }

  void tickAnimation(uint32_t now) {
    if (animPhase_ == ANIM_IDLE) return;
    switch (animPhase_) {
      case ANIM_Q1:   animQ1(now);   break;
      case ANIM_Q2:   animQ2(now);   break;
      case ANIM_Q3:   animQ3(now);   break;
      case ANIM_H1:   animH1(now);   break;
      case ANIM_H2:   animH2(now);   break;
      case ANIM_H3:   animH3(now);   break;
      case ANIM_HR1:  animHr1(now);  break;
      case ANIM_HR2:  animHr2(now);  break;
      case ANIM_HR3:  animHr3(now);  break;
      case ANIM_HR4:  animHr4(now);  break;
      case ANIM_HR5:  animHr5(now);  break;
      case ANIM_REM1: animRem1(now); break;
      case ANIM_REM2: animRem2(now); break;
      case ANIM_REM3: animRem3(now); break;
      case ANIM_REM4: animRem4(now); break;
      case ANIM_REM5: animRem5(now); break;
      case ANIM_REM6: animRem6(now); break;
      default: animPhase_ = ANIM_IDLE; break;
    }
    // Preview style overrides live only as long as the animation they were
    // set for; scheduled chimes afterwards must use the saved settings.
    // Same for the reminder-palette flag: the next scheduled chime must
    // render in its own animation palette again.
    if (animPhase_ == ANIM_IDLE) {
      clearStyleOverrides();
      reminderPaletteActive_ = false;
    }
  }

  // ── Quarter animations (modes 1-3, 2000-2800ms) ──────────────────────────

  void animQ1(uint32_t now) {  // Slow Comet
    const uint32_t se = scaledElapsed(now - animStartMs_);
    const uint32_t dur = 2500;
    if (se >= dur) { animPhase_ = ANIM_IDLE; return; }
    const uint8_t tl = animTl();
    strip_.setBrightness(animEnv(se, dur, 300, 300));
    uint8_t pos = (uint8_t)(se * 60u / dur);
    uint32_t c = bandColor(0, (uint8_t)(pos * 4u));
    setRingPixel(RING_OUTER_60, pos, c);
    for (uint8_t t = 1; t <= tl; t++)
      setRingPixel(RING_OUTER_60, (pos + 60u - t) % 60u, scale(c, trailLevel(t, tl)));
  }

  void animQ2(uint32_t now) {  // Dual Orbit — mirrored, quarter-turn staggered
    const uint32_t se = scaledElapsed(now - animStartMs_);
    const uint32_t dur = 2800;
    if (se >= dur) { animPhase_ = ANIM_IDLE; return; }
    const uint8_t tl = animTl();
    strip_.setBrightness(animEnv(se, dur, 300, 300));
    // Was a single pair of orbiters on the outer ring. Now every ring carries
    // the pair, each ring a quarter turn ahead of the one outside it and
    // counter-rotating against it (choreoPos) — two mirrored spirals rather
    // than one lonely lap.
    for (uint8_t r = 0; r < 3; r++) {
      const RingConfig &ring = ringByIdx(r);
      const uint8_t n = ring.count;
      const uint32_t travelled = (uint32_t)se * 2u * n / dur;  // two revolutions
      const uint8_t posA = choreoPos(ring, r, travelled);
      const uint8_t posB = (uint8_t)((posA + n / 2u) % n);     // 180° apart
      // Second orbiter uses the center band as an accent so the pair reads as
      // two distinct orbiters rather than a duplicate of the first.
      const uint32_t cA = bandColor(r, 0);
      const uint32_t cB = bandColor(3, 192);
      setRingPixel(ring, posA, cA);
      setRingPixel(ring, posB, cB);
      for (uint8_t t = 1; t <= tl && t < n / 2u; t++) {
        const uint8_t tbr = trailLevel(t, tl);
        setRingPixel(ring, choreoTrail(ring, r, posA, t), scale(cA, tbr));
        setRingPixel(ring, choreoTrail(ring, r, posB, t), scale(cB, tbr));
      }
    }
  }

  void animQ3(uint32_t now) {  // Bloom Ripple
    const uint32_t se = scaledElapsed(now - animStartMs_);
    // The outer ring (last band, onset 800) reaches zero brightness at local
    // t=1500, i.e. se=2300 — dur used to run to 2500, leaving 200ms of pure
    // black before the animation officially ended and the next one chained
    // in. That baked-in dead-black hold is what read as "halting" on camera:
    // ripple fades to black, holds black, then a new ripple pops on abruptly.
    // Trimmed to end exactly when the last visible ring goes dark.
    const uint32_t dur = 2300;
    if (se >= dur) { animPhase_ = ANIM_IDLE; return; }
    strip_.setBrightness(animBr());
    // Ripple outward: center → inner → middle → outer
    static const uint32_t onsets[] = {0, 250, 500, 800};
    for (uint8_t r = 0; r < 4; r++) {
      if (se < onsets[r]) continue;
      uint32_t t = se - onsets[r];
      uint8_t pct;
      if      (t < 450u)  pct = ease8((uint8_t)(t * 255u / 450u));
      else if (t < 650u)  pct = 255u;
      else if (t < 1500u) pct = ease8((uint8_t)(255u - (t - 650u) * 255u / 850u));
      else                pct = 0u;
      if (pct == 0u) continue;
      // Flower-part coloring, center outward, straight off the clock face:
      // center → inner-hour → middle-hour → outer-marker, each ring in its own
      // configured color via bloomColor(). Spreading frac across each ring lets
      // the flower LUT palettes sweep a gradient around the ring instead of
      // painting all 60/24 pixels at one fixed position.
      switch (r) {
        case 0:
          setCenterPixel(scale(bloomColor(3, 0), pct));
          break;
        case 1:
          for (uint8_t i = 0; i < RING_INNER_12.count; i++)
            setRingPixel(RING_INNER_12, i, scale(bloomColor(2, (uint8_t)(i * 21u)), pct));
          break;
        case 2:
          for (uint8_t i = 0; i < RING_MIDDLE_24.count; i++)
            setRingPixel(RING_MIDDLE_24, i, scale(bloomColor(1, (uint8_t)(i * 10u)), pct));
          break;
        case 3:
          for (uint8_t i = 0; i < RING_OUTER_60.count; i++)
            setRingPixel(RING_OUTER_60, i, scale(bloomColor(0, (uint8_t)(i * 4u)), pct));
          break;
      }
    }
  }

