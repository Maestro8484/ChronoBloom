// ===================== Demo Mode =====================
class DemoMode {
 public:
  struct Step {
    uint32_t duration_ms;
    const char *subtitle;
  };

  explicit DemoMode(ClockRenderer &renderer, LuxSensor &luxSensor, SettingsStore &settings)
      : renderer_(renderer), luxSensor_(luxSensor), settings_(settings) {}

  // preRollMs: hold the clock fully dark for this long before the reel opens.
  // It exists for filming -- start the recording, let the camera settle, and the
  // first frame of the reel is a fade-up from clean black instead of whatever
  // the face happened to be showing. 0 = open immediately (pre-2.30.0 behaviour).
  void start(uint32_t preRollMs = 0) {
    active_ = true;
    step_ = 0;
    stepStartMs_ = millis();
    subStep_ = 0;
    renderer_.clearStyleOverrides();
    renderer_.clearReel();  // never let a latched reel mode linger under the on-device demo
    // Open the reel with a gentle fade-up from black instead of a hard cut-in.
    breatherStartMs_ = 0;
    breatherFadeOut_ = false;
    wasAnimating_ = false;
    renderer_.setMasterFade(0);
    preRollEndMs_ = preRollMs ? (millis() + preRollMs) : 0;
    // With a pre-roll the fade-up is armed when the countdown expires, not now.
    fadeInStartMs_ = preRollMs ? 0 : millis();
  }

  void stop() {
    active_ = false;
    luxSensor_.clearLuxOverride();
    renderer_.clearStyleOverrides();
    // Hand the display back to normal rendering at full brightness.
    breatherStartMs_ = 0;
    fadeInStartMs_ = 0;
    preRollEndMs_ = 0;
    renderer_.setMasterFade(255);
  }

  bool active() const { return active_; }

  // Whether the live clock face should be rendered right now (when no animation
  // is playing). The face is legitimate content only during the face-based
  // steps (intro / center beat / brightness / end card) and while dissolving
  // OUT of one (a fade-out breather). During animation steps — including the
  // dark breather between two animations — this returns false so the caller
  // renders pure black instead, structurally preventing any face flash.
  bool rendersFaceNow() const {
    if (!active_) return false;
    if (preRollEndMs_ != 0) return false;                // capture pre-roll → pure black
    if (breatherStartMs_ != 0) return breatherFadeOut_;  // fade-out → face; snap → black
    return isFaceStep(step_);
  }

  // Two 1.5s-slope dim/bright lux-override cycles — the auto-brightness
  // showcase. Ticked independently of the main step_ sequence so it can also
  // run standalone via POST /demo/brightnessCycle: previously this segment
  // only existed inside the fixed stock demo (step 7), so an external
  // sequencer like the demo reel designer's Live Run had no way to trigger
  // it and could only sleep through a static, unchanging clock face.
  static float brightnessCycleLux(uint32_t elapsed) {
    if (elapsed < 1500)  { float t = elapsed / 1500.0f; return 220.0f - (220.0f - 1.0f) * t; }
    if (elapsed < 3000)  return 1.0f;
    if (elapsed < 4500)  { float t = (elapsed - 3000) / 1500.0f; return 1.0f + (220.0f - 1.0f) * t; }
    if (elapsed < 6000)  return 220.0f;
    if (elapsed < 7500)  { float t = (elapsed - 6000) / 1500.0f; return 220.0f - (220.0f - 1.0f) * t; }
    if (elapsed < 9000)  return 1.0f;
    if (elapsed < 10500) { float t = (elapsed - 9000) / 1500.0f; return 1.0f + (220.0f - 1.0f) * t; }
    return 220.0f;
  }

  void startBrightnessCycle(uint32_t durMs = 14000) {
    standaloneBrightness_ = true;
    standaloneBrightnessStartMs_ = millis();
    standaloneBrightnessDurMs_ = durMs;
  }

  void loop(uint32_t now) {
    if (standaloneBrightness_) {
      // Guard unsigned underflow: `now` is snapshotted at loop-top, but
      // startBrightnessCycle() sets standaloneBrightnessStartMs_ later in the
      // SAME loop iteration (inside webUi.loop()'s POST handler), so on that
      // first iteration now < startMs. Without this clamp `se` underflows to
      // ~4.29e9, immediately trips the done-branch below, and the standalone
      // cycle self-cancels before it ever calls setLuxOverride() — which is why
      // POST /demo/brightnessCycle drove no brightness change (observed 2.25.0).
      uint32_t se = (now >= standaloneBrightnessStartMs_)
                        ? (now - standaloneBrightnessStartMs_) : 0;
      if (se >= standaloneBrightnessDurMs_) {
        luxSensor_.clearLuxOverride();
        standaloneBrightness_ = false;
      } else {
        luxSensor_.setLuxOverride(brightnessCycleLux(se));
      }
    }
    if (!active_) return;

    // Capture pre-roll: hold the display dark and the sequence frozen until the
    // countdown expires. rendersFaceNow() reports false throughout, so the main
    // loop draws pure black and the recording opens on a clean frame. Signed
    // comparison so the millis() rollover case doesn't strand the countdown.
    if (preRollEndMs_ != 0) {
      if ((int32_t)(now - preRollEndMs_) < 0) {
        renderer_.setMasterFade(0);
        return;
      }
      preRollEndMs_ = 0;
      stepStartMs_ = now;    // step 0's clock starts here, not back at start()
      fadeInStartMs_ = now;  // and the reel fades up out of the black
    }

    // Arm a breather the instant an animation finishes so that anim->anim and
    // anim->step transitions dissolve through a calm dark beat instead of a
    // hard cut. Snap-to-black (no fade-out): the animation already released to
    // near-black in its own final frames, so cutting the leftover to 0 is
    // invisible while guaranteeing the live face never flashes in behind it.
    const bool nowAnim = renderer_.animating();
    if (wasAnimating_ && !nowAnim) armBreather(now, /*fadeOut=*/false);
    wasAnimating_ = nowAnim;

    // Drive the master dimmer for the current transition (fade-out / hold /
    // fade-in). Runs before stepTick so this frame already reflects the fade,
    // and so the sequence helpers can gate on the breather being over.
    updateFade(now);

    // Re-dispatch immediately after a step transition so the new step's first
    // trigger fires in this same tick. Bounded to STEP_COUNT as a safety guard.
    for (uint8_t guard = 0; guard < STEP_COUNT && active_; guard++) {
      if (!stepTick(now)) break;
    }
  }

  // ── Transition controller (dissolve + breather) ──────────────────────────
  // Master-fade timeline: an optional fade-out, a HOLD of darkness (the
  // breather), then a fade-in. Face-based step boundaries fade the lit face
  // out first; animation boundaries snap to black (the animation self-faded).
  void armBreather(uint32_t now, bool fadeOut) {
    if (breatherStartMs_ != 0) return;  // already breathing
    breatherStartMs_ = now;
    breatherFadeOut_ = fadeOut;
  }

  bool inBreather() const { return breatherStartMs_ != 0; }

  void updateFade(uint32_t now) {
    uint8_t mf = 255;
    if (breatherStartMs_ != 0) {
      const uint32_t e = now - breatherStartMs_;
      const uint32_t fadeOut = breatherFadeOut_ ? FADE_MS : 0;
      if (e < fadeOut) {
        mf = (uint8_t)(255u - 255u * e / fadeOut);      // fade the lit face out
      } else if (e < fadeOut + HOLD_MS) {
        mf = 0;                                          // hold dark — the breather
      } else {
        breatherStartMs_ = 0;                            // breather done
        fadeInStartMs_ = now;                            // begin fading the next in
        mf = 0;
      }
    }
    if (breatherStartMs_ == 0 && fadeInStartMs_ != 0) {
      const uint32_t e = now - fadeInStartMs_;
      if (e < FADE_MS) mf = (uint8_t)(255u * e / FADE_MS);
      else { fadeInStartMs_ = 0; mf = 255; }
    }
    renderer_.setMasterFade(mf);
  }

  // Runs the current step; returns true if it just transitioned to a new
  // step (caller should re-invoke immediately so the new step's first
  // trigger fires in the same tick), false otherwise.
  bool stepTick(uint32_t now) {
    uint32_t elapsed = now - stepStartMs_;

    // Step 0: Idle intro (8s)
    if (step_ == 0) {
      if (elapsed >= 8000) { advanceStep(now); return true; }
      return false;
    }

    // Steps 1-3: the clock's real chimes, exactly as configured — each slot
    // fires its *configured* trigger (not a hardcoded phase list) twice, so
    // the demo always mirrors what this unit actually does at :15/:30/:00
    // in its own palette, speed, brightness, and trail settings. Fewer
    // styles with more dwell time reads better than a rapid-fire catalog
    // of every mode.
    if (step_ == 1) {
      if (advanceConfiguredSeq(now, 0, 2)) { advanceStep(now); return true; }
      return false;
    }
    if (step_ == 2) {
      if (advanceConfiguredSeq(now, 1, 2)) { advanceStep(now); return true; }
      return false;
    }
    if (step_ == 3) {
      if (advanceConfiguredSeq(now, 2, 2)) { advanceStep(now); return true; }
      return false;
    }

    // Step 4: showcase — the big all-ring hour animations (Ceremony, Galaxy
    // Spin, Supernova, Comet Relay) played once each, full duration, in the
    // clock's own colors. Galaxy Spin and Comet Relay are the spiral/galaxy
    // pieces the enhancement pass targeted, so both are on camera here.
    if (step_ == 4) {
      static const AnimPhase showPhases[] = {ANIM_HR1, ANIM_HR2, ANIM_HR3, ANIM_HR4};
      if (advanceAnimPhaseSeq(now, showPhases, 4)) { advanceStep(now); return true; }
      return false;
    }

    // Step 5: focus reminder nudges — a varied but uniformly gentle set
    // (Gentle Pulse → Ripple In → Heartbeat → Slow Bloom → Firefly) so the
    // demo shows every nudge reading as a soft swell or quiet twinkle,
    // never an alert flash.
    if (step_ == 5) {
      static const uint8_t remModes[] = {6, 8, 9, 10, 11};  // REM1, REM3, REM4, REM5, REM6
      if (advanceReminderSeq(now, remModes, 5)) { advanceStep(now); return true; }
      return false;
    }

    // Step 6: Center LED beat (6s) — the stamen heart doubles as a live
    // status indicator (Wi-Fi today; temperature-sensor ready). Force a
    // green STATUS_WIFI_OK pulse so the camera sees it doing its job.
    if (step_ == 6) {
      if (subStep_ == 0) { renderer_.setStatus(STATUS_WIFI_OK, 6000); subStep_ = 1; }
      if (elapsed >= 6000) { advanceStep(now); return true; }
      return false;
    }

    // Step 7: Auto-brightness (14s) - two quick dim/bright cycles, showcasing
    // the faster 150ms lux-poll response (was 500ms, ~3-4x slower to react).
    if (step_ == 7) {
      if (elapsed >= 14000) { luxSensor_.clearLuxOverride(); advanceStep(now); return true; }
      luxSensor_.setLuxOverride(brightnessCycleLux(elapsed));
      return false;
    }

    // Step 8: End card (10s) - idle, subtitle shown
    if (step_ == 8) {
      if (elapsed >= 10000) {
        active_ = false;
        luxSensor_.clearLuxOverride();
        renderer_.setMasterFade(255);  // hand the display back at full brightness
      }
      return false;
    }
    return false;
  }

  String statusJson() const {
    if (!active_) return "{\"active\":false}";

    uint32_t now = millis();

    // Still counting down to the reel: report the remaining pre-roll so the web
    // UI and the /demo/overlay page can show the operator when to expect frame one.
    if (preRollEndMs_ != 0) {
      const int32_t remain = (int32_t)(preRollEndMs_ - now);
      char pbuf[128];
      snprintf(pbuf, sizeof(pbuf),
               "{\"active\":true,\"preroll\":true,\"preroll_ms\":%lu,"
               "\"step\":0,\"steps\":%u,\"subtitle\":\"Pre-roll: clock dark, reel about to open\","
               "\"elapsed_ms\":0,\"step_duration_ms\":%lu}",
               (unsigned long)(remain > 0 ? remain : 0), (unsigned)STEP_COUNT,
               (unsigned long)steps[0].duration_ms);
      return String(pbuf);
    }

    uint32_t elapsed = now - stepStartMs_;
    uint32_t duration = steps[step_].duration_ms;

    char buf[256];
    snprintf(buf, sizeof(buf),
             "{\"active\":true,\"preroll\":false,\"step\":%u,\"steps\":%u,\"subtitle\":\"%s\","
             "\"elapsed_ms\":%lu,\"step_duration_ms\":%lu}",
             (unsigned)step_, (unsigned)STEP_COUNT, steps[step_].subtitle,
             (unsigned long)elapsed, (unsigned long)duration);
    return String(buf);
  }

 private:
  // Steps with no animation-driven sequence: the idle intro, the center-LED
  // beat, the auto-brightness cycle, and the end card. Their transitions have
  // no animation whose end arms the dissolve, so advanceStep() fades them out.
  static bool isFaceStep(uint8_t s) { return s == 0 || s >= 6; }

  void advanceStep(uint32_t now) {
    const bool leavingFaceStep = isFaceStep(step_);
    step_++;
    stepStartMs_ = now;
    subStep_ = 0;
    // Fade the lit face out on the way to the next step. Animation steps
    // already breathed when their final animation ended (snap-to-black), so
    // only the face steps need the explicit fade-out here.
    if (leavingFaceStep) armBreather(now, /*fadeOut=*/true);
  }

  // Plays phases[0..count) one after another. Each next phase is triggered only
  // once the current animation has finished AND the post-animation breather has
  // elapsed (armed in loop()), so consecutive pieces dissolve through a calm
  // dark beat and fade back in rather than hard-cutting. Returns true once
  // every phase has been triggered, finished, and breathed out.
  bool advanceAnimPhaseSeq(uint32_t now, const AnimPhase *phases, uint8_t count) {
    if (renderer_.animating() || inBreather()) return false;
    if (subStep_ < count) {
      renderer_.triggerAnimDirect(phases[subStep_], now);
      subStep_++;
      return false;
    }
    return true;
  }

  // Same immediate-chain pacing as advanceAnimPhaseSeq, but fires the
  // clock's *configured* animation for a chime slot (0=quarter, 1=half-hour,
  // 2=hour) `count` times. If that slot's configured mode is 0 (off), the
  // trigger no-ops and the sequence falls through without stalling.
  bool advanceConfiguredSeq(uint32_t now, uint8_t slot, uint8_t count) {
    if (renderer_.animating() || inBreather()) return false;
    if (subStep_ < count) {
      if (slot == 0)      renderer_.triggerQuarterAnimation(now);
      else if (slot == 1) renderer_.triggerHalfHourAnimation(now);
      else                renderer_.triggerHourAnimation(now);
      subStep_++;
      return false;
    }
    return true;
  }

  // Same pacing, but plays an explicit list of reminder modes (6..10 map to
  // ANIM_REM1..5), allowing repeats.
  bool advanceReminderSeq(uint32_t now, const uint8_t *modes, uint8_t count) {
    if (renderer_.animating() || inBreather()) return false;
    if (subStep_ < count) {
      renderer_.triggerReminderDirectAnimation(modes[subStep_], now);
      subStep_++;
      return false;
    }
    return true;
  }

  // Approximate wall-clock durations for the web UI progress bar. The
  // animation-driven steps are event-paced (each animation runs to its
  // natural end before the next is triggered) and steps 1-3 depend on which
  // styles are configured, so these are estimates at animationSpeed 3 with
  // the maintainer's configuration (Bloom Ripple / Unfurl / Comet Relay),
  // not exact bounds. Each piece-to-piece transition now adds a ~0.8s
  // dissolve+breather, so these include that padding.
  static constexpr Step steps[] = {
    {8800,  "ChronoBloom — ESP32-C3 NeoPixel clock"},
    {5600,  "Quarter-hour chime — twice, exactly as configured"},
    {11000, "Half-hour chime — twice, exactly as configured"},
    {17000, "Top-of-hour chime — twice, exactly as configured"},
    {36500, "Hour animation showcase — Ceremony, Galaxy Spin, Supernova, Comet Relay"},
    {20000, "Focus reminder nudges — gentle, subtle, never a flash"},
    {6800,  "Center LED — live Wi-Fi / status indicator, sensor-ready"},
    {14850, "Auto-brightness — VEML7700 sensor, now 3-4x faster response"},
    {10850, "Open source — github / printables / hackaday.io"}
  };
  static constexpr uint8_t STEP_COUNT = sizeof(steps) / sizeof(steps[0]);

  bool active_ = false;
  uint8_t step_ = 0;
  uint8_t subStep_ = 0;
  uint32_t stepStartMs_ = 0;
  bool standaloneBrightness_ = false;
  uint32_t standaloneBrightnessStartMs_ = 0;
  uint32_t standaloneBrightnessDurMs_ = 14000;
  // Cross-dissolve / breather state (see updateFade / armBreather).
  static constexpr uint32_t FADE_MS = 450;  // dissolve in/out duration
  static constexpr uint32_t HOLD_MS = 400;  // dark breather hold between pieces
  uint32_t preRollEndMs_ = 0;               // 0 = not pre-rolling; else absolute millis the reel opens
  uint32_t breatherStartMs_ = 0;            // 0 = not breathing
  bool breatherFadeOut_ = false;            // fade the face out first, vs snap to black
  uint32_t fadeInStartMs_ = 0;              // 0 = not fading in
  bool wasAnimating_ = false;               // edge-detect animation end
  ClockRenderer &renderer_;
  LuxSensor &luxSensor_;
  SettingsStore &settings_;
};

