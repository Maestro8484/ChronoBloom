// ===================== Focus Reminder Scheduler =====================
class FocusReminderScheduler {
 public:
  explicit FocusReminderScheduler(TimeModel &model, ClockRenderer &renderer, SettingsStore &settings)
      : model_(model), renderer_(renderer), settings_(settings) {}

  void checkAndFire(uint32_t now) {
    const ClockSettings &s = settings_.get();
    if (!s.focusReminder_enabled) {
      // Disabling reminders clears all RAM scheduling state, so nothing can
      // strand across a disable/re-enable (a stranded repeatPending_ used to
      // be able to fire a swell at any hour weeks later) and a stale ack
      // window can't eat time-adjust presses after a millis() wrap.
      repeatPending_ = false;
      firesSinceAck_ = 0;
      lastFireMs_ = 0;
      ackUntilMs_ = 0;
      return;
    }

    ClockTime t = model_.get();

    // No days selected = never fire (matches pre-existing semantics).
    if (s.focusReminder_daysMask == 0) return;

    // Day-of-week comes from the system epoch (set only by NTP). If the epoch
    // was never synced (offline boot, time set via buttons/web), tm_wday is a
    // 1970 artifact — skip the day filter rather than silently never firing.
    // The hour window below still applies; it uses TimeModel, not the epoch.
    if (time(nullptr) >= 1700000000) {
      uint8_t dow = getDayOfWeek();
      if (!(s.focusReminder_daysMask & (1 << dow))) return;
    }

    // Time window check
    bool inWindow = false;
    if (s.focusReminder_startHour < s.focusReminder_endHour) {
      // Normal window (e.g., 08:00-22:00)
      inWindow = (t.hour >= s.focusReminder_startHour && t.hour < s.focusReminder_endHour);
    } else if (s.focusReminder_startHour > s.focusReminder_endHour) {
      // Wrapped window (e.g., 22:00-08:00, crosses midnight)
      inWindow = (t.hour >= s.focusReminder_startHour || t.hour < s.focusReminder_endHour);
    } else {
      // start == end (v2.31.0): treat as a 24-hour window. The old behavior
      // silently never fired, which read as broken to anyone meaning "all day".
      inWindow = true;
    }
    if (!inWindow) return;

    // Escalation repeat (v2.31.0): the second and later unacknowledged nudges
    // play a second swell a few seconds after the first, so a nudge that went
    // unnoticed in peripheral vision asks twice. Deliberately AFTER the
    // day/window checks: a repeat straddling the window edge is dropped
    // rather than played into quiet hours. RAM-only state.
    if (repeatPending_ && lastFireMs_ != 0 && now - lastFireMs_ >= REPEAT_DELAY_MS) {
      repeatPending_ = false;
      triggerReminderAnimation(s.focusReminder_animation, now);
      ackUntilMs_ = now + ACK_WINDOW_MS;  // the repeat is still acknowledgeable
      Serial.printf("[FocusReminder] Escalation swell (%u fires unacknowledged)\n",
                    (unsigned)firesSinceAck_);
    }

    // Interval check: enough time since last fire?
    uint32_t intervalMs = static_cast<uint32_t>(s.focusReminder_intervalMinutes) * 60000UL;
    if (lastFireMs_ != 0 && now - lastFireMs_ < intervalMs) return;

    // Fire animation (reuse existing renderer methods)
    triggerReminderAnimation(s.focusReminder_animation, now);

    // Record fire time in RAM only — no EEPROM write needed
    lastFireMs_ = now;
    ackUntilMs_ = now + ACK_WINDOW_MS;
    if (firesSinceAck_ < 255) firesSinceAck_++;
    repeatPending_ = (firesSinceAck_ >= 2);

    Serial.printf("[FocusReminder] Fired at %02d:%02d (interval=%d min, unacked=%u)\n",
                  t.hour, t.minute, s.focusReminder_intervalMinutes,
                  (unsigned)firesSinceAck_);
  }

  // True while a button press should read as "I saw it" rather than a time
  // adjustment. The window opens ONLY at fire time (ackUntilMs_) and closes
  // on acknowledgment — acknowledge() must never extend it, or every
  // subsequent press (including hold-to-repeat time adjustment) would be
  // eaten as another ack and the buttons would stay dead to time-setting.
  // Signed delta so a stale deadline is harmless across millis() wrap.
  bool ackWindowActive(uint32_t now) const {
    return ackUntilMs_ != 0 && (int32_t)(ackUntilMs_ - now) > 0;
  }

  // Button acknowledgment (v2.31.0): closes the ack window, clears the
  // escalation counter, and restarts the interval from this moment. The very
  // next press adjusts time normally.
  void acknowledge(uint32_t now) {
    firesSinceAck_ = 0;
    repeatPending_ = false;
    lastFireMs_ = now;
    ackUntilMs_ = 0;
    Serial.println("[FocusReminder] Acknowledged by button — interval restarted");
  }

 private:
  uint8_t getDayOfWeek() {
    time_t now = time(nullptr);
    struct tm t;
    localtime_r(&now, &t);
    return static_cast<uint8_t>(t.tm_wday);  // 0=Sun … 6=Sat
  }

  void triggerReminderAnimation(uint8_t mode, uint32_t now) {
    renderer_.triggerReminderDirectAnimation(mode, now);
  }

  TimeModel &model_;
  ClockRenderer &renderer_;
  SettingsStore &settings_;
  uint32_t lastFireMs_ = 0;
  uint32_t ackUntilMs_ = 0;     // ack window deadline; set at fire time only, cleared by ack
  uint8_t firesSinceAck_ = 0;   // nudges since the last button acknowledgment (RAM only)
  bool repeatPending_ = false;  // escalation: play a second swell after the current fire
  static constexpr uint32_t REPEAT_DELAY_MS = 6000;   // past the longest nudge animation (~4.4s)
  static constexpr uint32_t ACK_WINDOW_MS = 15000;    // press within this of a fire = acknowledge
};

class ButtonInput {
 public:
  enum class HoldPhase : uint8_t { IDLE, REPEAT_MIN, REPEAT_HOUR };

  void begin() {
    pinMode(BUTTON_UP_PIN, INPUT_PULLUP);
    pinMode(BUTTON_DOWN_PIN, INPUT_PULLUP);
  }

  void poll(uint32_t now) {
    bool upNow   = (digitalRead(BUTTON_UP_PIN)   == LOW);
    bool downNow = (digitalRead(BUTTON_DOWN_PIN) == LOW);

    // --- UP button ---
    if (upNow && !lastUp_ && now - lastUpMs_ > kDebounceMs) {
      // Fresh press: debounce passed, leading edge
      upPressed_     = true;
      upPressedAt_   = now;
      upLastRepeat_  = now;
      upPhase_       = HoldPhase::IDLE;
      lastUpMs_      = now;
    } else if (upNow && lastUp_) {
      // Held: advance hold phase and fire repeats
      uint32_t held = now - upPressedAt_;
      if (held >= kStuckHoldMs) {
        // Stuck-button guard (M5): a continuous hold this long is almost
        // certainly a failed/shorted switch, not a human. Suppress repeats until
        // a real release edge so a stuck button can't wind the clock away
        // (±60 min per hour-phase repeat) and spam status animations forever.
        if (!upStuck_) { upStuck_ = true; Serial.println("[BTN] UP held >30s — treating as stuck; repeats suppressed until release."); }
        upPhase_ = HoldPhase::IDLE;
      } else if (held >= kHoldHourMs) {
        upPhase_ = HoldPhase::REPEAT_HOUR;
      } else if (held >= kHoldRepeatMs) {
        if (upPhase_ == HoldPhase::IDLE) upPhase_ = HoldPhase::REPEAT_MIN;
      }
      if (!upStuck_ && upPhase_ != HoldPhase::IDLE && now - upLastRepeat_ >= kRepeatIntervalMs) {
        upRepeat_     = true;
        upLastRepeat_ = now;
      }
    } else if (!upNow) {
      // Released
      upPhase_ = HoldPhase::IDLE;
      upStuck_ = false;  // real release clears the stuck latch
    }

    // --- DOWN button ---
    if (downNow && !lastDown_ && now - lastDownMs_ > kDebounceMs) {
      downPressed_     = true;
      downPressedAt_   = now;
      downLastRepeat_  = now;
      downPhase_       = HoldPhase::IDLE;
      lastDownMs_      = now;
    } else if (downNow && lastDown_) {
      uint32_t held = now - downPressedAt_;
      if (held >= kStuckHoldMs) {
        // Stuck-button guard (M5) — see the UP branch. GPIO9 (DOWN) is the more
        // likely offender: it's also the BOOT strapping pin, so a flaky/shorted
        // DOWN switch is a realistic failure.
        if (!downStuck_) { downStuck_ = true; Serial.println("[BTN] DOWN held >30s — treating as stuck; repeats suppressed until release."); }
        downPhase_ = HoldPhase::IDLE;
      } else if (held >= kHoldHourMs) {
        downPhase_ = HoldPhase::REPEAT_HOUR;
      } else if (held >= kHoldRepeatMs) {
        if (downPhase_ == HoldPhase::IDLE) downPhase_ = HoldPhase::REPEAT_MIN;
      }
      if (!downStuck_ && downPhase_ != HoldPhase::IDLE && now - downLastRepeat_ >= kRepeatIntervalMs) {
        downRepeat_     = true;
        downLastRepeat_ = now;
      }
    } else if (!downNow) {
      downPhase_ = HoldPhase::IDLE;
      downStuck_ = false;  // real release clears the stuck latch
    }

    lastUp_   = upNow;
    lastDown_ = downNow;
  }

  // Returns non-zero delta if a press or repeat fired, 0 otherwise.
  // Positive = UP direction, negative = DOWN direction.
  int consumeUp() {
    if (upPressed_) { upPressed_ = false; ++g_buttonEventCount; return 1; }
    if (upRepeat_)  { upRepeat_  = false; ++g_buttonEventCount;
                      return (upPhase_ == HoldPhase::REPEAT_HOUR) ? 60 : 1; }
    return 0;
  }
  int consumeDown() {
    if (downPressed_) { downPressed_ = false; ++g_buttonEventCount; return -1; }
    if (downRepeat_)  { downRepeat_  = false; ++g_buttonEventCount;
                        return (downPhase_ == HoldPhase::REPEAT_HOUR) ? -60 : -1; }
    return 0;
  }

  // Legacy single-press API kept for any callers that only care about edge.
  bool consumeUpPress()   { return consumeUp()   != 0; }
  bool consumeDownPress() { return consumeDown() != 0; }

 private:
  static constexpr uint32_t kDebounceMs      =  50;
  static constexpr uint32_t kHoldRepeatMs    = 500;
  static constexpr uint32_t kRepeatIntervalMs= 150;
  static constexpr uint32_t kHoldHourMs      = 2000;
  static constexpr uint32_t kStuckHoldMs     = 30000;  // hold ceiling (M5): beyond this, treat as a stuck switch

  bool upPressed_   = false;
  bool downPressed_ = false;
  bool upRepeat_    = false;
  bool downRepeat_  = false;
  bool lastUp_      = false;
  bool lastDown_    = false;
  bool upStuck_     = false;
  bool downStuck_   = false;

  uint32_t lastUpMs_      = 0;
  uint32_t lastDownMs_    = 0;
  uint32_t upPressedAt_   = 0;
  uint32_t downPressedAt_ = 0;
  uint32_t upLastRepeat_  = 0;
  uint32_t downLastRepeat_= 0;

  HoldPhase upPhase_   = HoldPhase::IDLE;
  HoldPhase downPhase_ = HoldPhase::IDLE;
};

