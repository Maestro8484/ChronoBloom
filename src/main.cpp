    server_.on("/settings", HTTP_POST, [&]() {
      // Never commit settings to flash while a firmware update is writing the
      // OTA partition. On the single-core C3 the two flash operations collide
      // and can corrupt the half-written OTA image (observed 2026-07-08:
      // saving settings mid-OTA bricked a unit into a multi-power-cycle
      // recovery). Update.isRunning() covers both the HTTP /update path and
      // ArduinoOTA. Preview (non-persistent) is unaffected — it never writes.
      if (Update.isRunning()) { sendClose(503, "text/plain", "Firmware update in progress — settings locked"); return; }
      // Timezone is handled here rather than in applyPostedSettings(): it is not
      // a ClockSettings field (it lives in NVS, see namespace tzone) and it is
      // the one posted value that can be rejected, so it answers 400 instead of
      // silently storing a string that would mean UTC.
      if (server_.hasArg("timezone")) {
        if (!timeSync_.setTimezone(server_.arg("timezone"))) {
          sendClose(400, "text/plain", "Invalid timezone: expected a POSIX TZ string, e.g. MST7MDT,M3.2.0,M11.1.0");
          return;
        }
      }
      settings_.update(applyPostedSettings(settings_.getPersisted()));
      settings_.clearPreview();  // a real save supersedes any in-flight preview
      if (!server_.hasArg("silent")) renderer_.setStatus(STATUS_SETTINGS_SAVED, 1300);
      model_.markDirty();
      sendClose(200, "text/plain", "ok");
    });

    // Non-persistent "Preview on clock": render the posted settings for a short
    // TTL with NO EEPROM write, then auto-revert to the saved face (tickPreview
    // in loop()). Safe during OTA — it never writes flash. Same arg set as
    // POST /settings; `ttl` ms optional (default 10000, clamped 1000..30000).
    server_.on("/settings/preview", HTTP_POST, [&]() {
      uint32_t ttl = server_.hasArg("ttl") ? (uint32_t)server_.arg("ttl").toInt() : 10000u;
      if (ttl < 1000u)  ttl = 1000u;
      if (ttl > 30000u) ttl = 30000u;
      settings_.setPreview(applyPostedSettings(settings_.getPersisted()), millis(), ttl);
      model_.markDirty();
      sendClose(200, "text/plain", "ok");
    });
