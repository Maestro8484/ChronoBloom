// H2: cancel the OTA rollback watch once the boot is known-good.
//
// IMPORTANT LIMITATION: this only has an effect if the *bootloader* was built
// with CONFIG_BOOTLOADER_APP_ROLLBACK_ENABLE=y. The PlatformIO `framework =
// arduino` build ships a *precompiled* bootloader that does NOT set it, and it
// cannot be toggled by a build flag (it requires rebuilding the bootloader from
// a custom sdkconfig, e.g. Arduino-as-IDF-component). So on the current build
// this is a deliberate, correct no-op: `esp_ota_get_state_partition()` reports
// VALID (never PENDING_VERIFY), so mark-valid is skipped. The call is wired now
// so that if a rollback-capable bootloader is ever adopted, an OTA image that
// boot-loops before reaching this point auto-reverts to the prior good image
// with no code change. See docs/HARDENING_AUDIT.md finding H2.
static void markBootValid() {
  static bool done = false;
  if (done) return;
  done = true;
  const esp_partition_t *running = esp_ota_get_running_partition();
  esp_ota_img_states_t state;
  if (esp_ota_get_state_partition(running, &state) != ESP_OK) return;
  if (state != ESP_OTA_IMG_PENDING_VERIFY) return;  // nothing to confirm today
  if (esp_ota_mark_app_valid_cancel_rollback() == ESP_OK) {
    Serial.println("[OTA] Boot confirmed good — image marked valid, rollback cancelled.");
  } else {
    Serial.println("[OTA] esp_ota_mark_app_valid_cancel_rollback() failed.");
  }
}

